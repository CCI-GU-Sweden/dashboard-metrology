-- PostgreSQL 15 baseline. Run once as a setup identity with CREATE ROLE and
-- ownership privileges. Existing objects cause an error and transaction rollback.
\set ON_ERROR_STOP on
BEGIN;
CREATE ROLE metrology_processor NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;

CREATE TABLE public.metrology_schema_version (
    version integer PRIMARY KEY, installed_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.metrology_schema_version(version) VALUES (1);
CREATE TABLE public.metrology_microscope (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE, location text
);
CREATE TABLE public.metrology_lens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    microscope_id bigint NOT NULL REFERENCES public.metrology_microscope(id),
    magnification text NOT NULL, numerical_aperture double precision,
    CONSTRAINT metrology_lens_identity UNIQUE NULLS NOT DISTINCT (microscope_id, magnification, numerical_aperture),
    CHECK (numerical_aperture IS NULL OR numerical_aperture > 0)
);
CREATE TABLE public.metrology_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL, group_id bigint NOT NULL, fileset_id bigint NOT NULL,
    analysis_version text NOT NULL, config_hash text NOT NULL,
    generation integer NOT NULL DEFAULT 1 CHECK (generation > 0),
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','running','analyzed','attaching','complete','retryable_failure','permanent_failure')),
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    lease_until timestamptz, error_message text, imported_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source, fileset_id, analysis_version, config_hash, generation)
);
CREATE INDEX metrology_run_queue_idx ON public.metrology_run (state, imported_at DESC, id);
CREATE TABLE public.metrology_run_input (
    run_id bigint NOT NULL REFERENCES public.metrology_run(id),
    image_id bigint NOT NULL, ordinal integer NOT NULL CHECK (ordinal >= 0),
    image_name text, metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (run_id, image_id), UNIQUE (run_id, ordinal)
);
CREATE TABLE public.metrology_measurement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES public.metrology_run(id),
    microscope_id bigint REFERENCES public.metrology_microscope(id),
    lens_id bigint REFERENCES public.metrology_lens(id),
    metric_key text NOT NULL, category text NOT NULL, measurement_type text NOT NULL,
    value double precision NOT NULL, unit text, acquired_at timestamptz,
    score double precision, status text NOT NULL DEFAULT 'success',
    UNIQUE (run_id, metric_key)
);
CREATE INDEX metrology_measurement_lens_time_idx ON public.metrology_measurement(lens_id, acquired_at);
CREATE TABLE public.metrology_artifact (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES public.metrology_run(id), artifact_key text NOT NULL,
    image_id bigint NOT NULL, mime_type text NOT NULL, checksum text,
    durable_location text, annotation_id bigint,
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','uploaded','linked','failed')),
    UNIQUE (run_id, artifact_key)
);
CREATE TABLE public.metrology_threshold (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category text NOT NULL, measurement_type text NOT NULL, magnification text NOT NULL,
    numerical_aperture double precision NOT NULL, expected_value double precision NOT NULL,
    lower_bound double precision, upper_bound double precision,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    UNIQUE (category, measurement_type, magnification, numerical_aperture, version),
    CHECK (lower_bound IS NULL OR upper_bound IS NULL OR lower_bound <= upper_bound)
);
CREATE TABLE public.metrology_setting (
    name text PRIMARY KEY, value jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.metrology_score (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    microscope_id bigint NOT NULL REFERENCES public.metrology_microscope(id),
    lens_id bigint REFERENCES public.metrology_lens(id),
    level text NOT NULL CHECK (level IN ('metric','category','lens','microscope')),
    score_key text NOT NULL, period_start timestamptz NOT NULL,
    scoring_version text NOT NULL, score double precision NOT NULL, status text NOT NULL,
    UNIQUE NULLS NOT DISTINCT (microscope_id, lens_id, level, score_key, period_start, scoring_version)
);
CREATE TABLE public.metrology_action (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_id bigint NOT NULL REFERENCES public.metrology_measurement(id),
    action text NOT NULL, actor_user_id bigint NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
    details jsonb NOT NULL DEFAULT '{}'::jsonb
);

GRANT USAGE ON SCHEMA public TO metrology_processor, filestats_dashboard;
GRANT SELECT ON public.metrology_schema_version TO metrology_processor, filestats_dashboard;
GRANT SELECT, INSERT, UPDATE ON public.metrology_microscope, public.metrology_lens,
    public.metrology_run, public.metrology_run_input, public.metrology_measurement,
    public.metrology_artifact, public.metrology_threshold, public.metrology_setting,
    public.metrology_score TO metrology_processor;
GRANT SELECT ON public.metrology_action TO metrology_processor;
GRANT SELECT ON public.metrology_microscope, public.metrology_lens, public.metrology_run,
    public.metrology_run_input, public.metrology_measurement, public.metrology_artifact,
    public.metrology_threshold, public.metrology_setting, public.metrology_score,
    public.metrology_action TO filestats_dashboard;
GRANT UPDATE (status) ON public.metrology_measurement TO filestats_dashboard;
GRANT INSERT ON public.metrology_action TO filestats_dashboard;
GRANT USAGE, SELECT ON SEQUENCE public.metrology_microscope_id_seq, public.metrology_lens_id_seq,
    public.metrology_run_id_seq, public.metrology_measurement_id_seq, public.metrology_artifact_id_seq,
    public.metrology_threshold_id_seq, public.metrology_score_id_seq TO metrology_processor;
GRANT USAGE, SELECT ON SEQUENCE public.metrology_action_id_seq TO filestats_dashboard;
COMMIT;
