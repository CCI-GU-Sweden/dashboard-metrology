\set ON_ERROR_STOP on
BEGIN;
DO $$ BEGIN
  IF (SELECT max(version) FROM public.metrology_schema_version) <> 4 THEN
    RAISE EXCEPTION 'Expected schema version 4';
  END IF;
END $$;
CREATE VIEW public.metrology_current_run AS
  SELECT DISTINCT ON (source, fileset_id) * FROM public.metrology_run
  WHERE state='complete' ORDER BY source,fileset_id,generation DESC,id DESC;
CREATE TABLE public.metrology_redo_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source text NOT NULL, fileset_id bigint NOT NULL,
  measurement_id bigint NOT NULL REFERENCES public.metrology_measurement(id),
  requested_by bigint NOT NULL, requested_at timestamptz NOT NULL DEFAULT now(),
  state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','running','failed','complete')),
  run_id bigint REFERENCES public.metrology_run(id),
  updated_at timestamptz NOT NULL DEFAULT now(), error_message text
);
CREATE UNIQUE INDEX metrology_redo_active_fileset ON public.metrology_redo_request(source,fileset_id)
  WHERE state IN ('pending','running');
GRANT SELECT ON public.metrology_current_run TO metrology_processor, filestats_dashboard;
GRANT SELECT, INSERT ON public.metrology_redo_request TO filestats_dashboard;
GRANT SELECT, UPDATE ON public.metrology_redo_request TO metrology_processor;
GRANT USAGE, SELECT ON SEQUENCE public.metrology_redo_request_id_seq TO filestats_dashboard;
INSERT INTO public.metrology_schema_version(version) VALUES (5);
COMMIT;
